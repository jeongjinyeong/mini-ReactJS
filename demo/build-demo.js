const { readFileSync, writeFileSync } = require('node:fs');
const { basename, join } = require('node:path');

function buildDemo(phase, modules) {
  const directory = join(__dirname, phase);
  const imports = Object.fromEntries(modules.map(file => {
    // Data URLs cannot resolve relative imports, so use the embedded module names.
    const source = readFileSync(join(directory, file), 'utf8')
      .replace(/(\bfrom\s+['"])((?:\.\.?\/)+[\w/-]+\.js)(?=['"])/g,
        (_, prefix, path) => prefix + 'mini-react/' + basename(path));
    const encoded = Buffer.from(source).toString('base64');
    return ['mini-react/' + basename(file), 'data:text/javascript;base64,' + encoded];
  }));

  const template = readFileSync(join(directory, 'index.html'), 'utf8');
  const entry = '<script type="module" src="./demo.js"></script>';
  if (!template.includes(entry)) {
    throw new Error('Could not find the Phase 1 demo module in index.html.');
  }

  const embeddedScripts = [
    '<script type="importmap">',
    JSON.stringify({ imports }, null, 2),
    '    </script>',
    '    <script type="module">import "mini-react/demo.js";</script>',
  ].join('\n');

  const standalone = template
    .replace(entry, embeddedScripts)
    .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by node demo/build-demo.js. Edit index.html and the JS modules. -->');
  writeFileSync(join(directory, 'demo.html'), standalone);
}

const engine = ['../../src/phase1/vnode.js', '../../src/phase1/diff.js', '../../src/phase1/patch.js'];
buildDemo('phase1', [...engine, 'demo.js']);
buildDemo('phase2', [...engine, '../../src/phase2/runtime.js', 'demo.js']);
